CREATE DATABASE IF NOT EXISTS secure_login_db;
USE secure_login_db;
CREATE TABLE IF NOT EXISTS app_users (
 id INT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(80) NOT NULL UNIQUE,
 email VARCHAR(150) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(20) NOT NULL DEFAULT 'USER', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS login_events (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NULL, username VARCHAR(80) NOT NULL,
 event_type VARCHAR(30) NOT NULL, event_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 ip_address VARCHAR(45) NULL,
 CONSTRAINT fk_login_event_user FOREIGN KEY (user_id) REFERENCES app_users(id) ON DELETE SET NULL
);
